function somar(numeroA, numeroB){
  const result = Number(numeroA) + Number(numeroB);

  alert(`O resultado é:  ${result}`);
}

function subtrair(numeroA, numeroB){
  const result = Number(numeroA) - Number(numeroB);

  alert(`O resultado é:  ${result}`);
}

function multiplicar(numeroA, numeroB){
  const result = Number(numeroA) * Number(numeroB);

  alert(`O resultado é:  ${result}`);
}

function dividir(numeroA, numeroB){
  const result = Number(numeroA) / Number(numeroB);

  alert(`O resultado é:  ${result}`);
}


